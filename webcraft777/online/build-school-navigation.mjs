// Refresh the worker's navigation data if src/school.ts is edited.
import { readFileSync, writeFileSync } from 'node:fs'
import { buildSchool, SCHOOL_BOUNDS, SCHOOL_LEVELS, schoolStairTop, schoolSpawn } from '../src/school.ts'

const {minX,maxX,minZ,maxZ}=SCHOOL_BOUNDS
const [lower,upper]=SCHOOL_LEVELS
const width=maxX-minX, depth=maxZ-minZ, area=width*depth
const blocks=new Uint8Array(area*(upper-lower+3))
const coordinate=(x,z)=>(x-minX)+width*(z-minZ)
const read=(x,y,z)=>blocks[coordinate(x,z)+area*(y-lower+1)]
buildSchool((x,y,z,id)=>{
  if(x>=minX&&x<maxX&&z>=minZ&&z<maxZ&&y>=lower-1&&y<=upper+1)
    blocks[coordinate(x,z)+area*(y-lower+1)]=id
})
const open=new Uint8Array(area), stairs=[]
for(let z=minZ;z<maxZ;z++)for(let x=minX;x<maxX;x++){
  const key=coordinate(x,z)
  for(let y=lower;y<=upper;y++){
    if(read(x,y-1,z)!==0&&read(x,y,z)===0&&read(x,y+1,z)===0)open[key]|=1<<(y-lower)
  }
  if(schoolStairTop(x,z)!==undefined)stairs.push(key)
}
const source=[
  '// Generated by online/build-school-navigation.mjs from the shipped school layout.',
  'export const schoolNavigation = '+JSON.stringify({minX,minZ,width,depth,lower,upper,spawn:schoolSpawn,
    open:Buffer.from(open).toString('base64'),stairs})+'\n',
].join('\n')
const output=new URL('./school-navigation.mjs',import.meta.url)
if(process.argv.includes('--check')){
  if(readFileSync(output,'utf8').replaceAll('\r\n','\n')!==source){
    console.error('School navigation data must be regenerated.')
    process.exitCode=1
  }
}else writeFileSync(output,source)
