// Refresh with node --experimental-transform-types online/build-cops-navigation.mjs.
// The Worker never loads the game bundle.
import { readFileSync, writeFileSync } from 'node:fs'
import { COPS_BOUNDS, COPS_SPAWNS, COPS_WALK_Y, parkStairTop } from '../src/cops-stages.ts'
import { World, isSolid } from '../src/world.ts'

const {minX,maxX,minZ,maxZ}=COPS_BOUNDS
const floor=COPS_WALK_Y, levels=16
const width=maxX-minX, depth=maxZ-minZ, area=width*depth
const tile=(x,z)=>x-minX+width*(z-minZ)
const bit=(y)=>1<<(y-floor)
const maps={}

for(const stage of ['park','crossing']){
  const world=new World('cops-navigation',false,2,stage)
  const columns=new Uint16Array(area), connected=new Uint16Array(area)
  const stairs=new Uint8Array(area)
  for(let z=minZ+1;z<maxZ-1;z++)for(let x=minX+1;x<maxX-1;x++){
    // The jail is only visited by rule-enforced transport. Its rescue pad is outside.
    if(x>=118&&x<=138&&z>=178&&z<=191) continue
    const index=tile(x,z)
    const stair=stage==='park'?parkStairTop(x,z):undefined
    if(stair!==undefined)stairs[index]=stair-floor
    const maxY=stage==='park'?floor+levels-1:floor
    for(let y=floor;y<=maxY;y++){
      const support=world.get(x,y-1,z)
      if(isSolid(support)&&support!==32&&world.get(x,y,z)===0&&world.get(x,y+1,z)===0)columns[index]|=bit(y)
    }
  }
  const spawn=COPS_SPAWNS.robbers
  const initial=tile(Math.floor(spawn.x),Math.floor(spawn.z))
  const queue=[initial]
  connected[initial]=1
  for(let index=0;index<queue.length;index++){
    const node=queue[index], cell=node%area, level=Math.floor(node/area)
    for(const delta of [-width,-1,1,width]){
      const next=cell+delta
      if(columns[next]&1<<level){
        if(!(connected[next]&1<<level)){
          connected[next]|=1<<level
          queue.push(next+level*area)
        }
        continue
      }
      for(const step of [1,-1]){
        const nextLevel=level+step
        if(nextLevel<0||nextLevel>=levels||!(columns[next]&1<<nextLevel)||connected[next]&1<<nextLevel)continue
        if(!(level>0&&stairs[cell]===level)&&!(nextLevel>0&&stairs[next]===nextLevel))continue
        const lower=step>0?cell:next
        const lowX=minX+lower%width, lowZ=minZ+Math.floor(lower/width)
        if(world.get(lowX,floor+Math.max(level,nextLevel)+1,lowZ)!==0)continue
        connected[next]|=1<<nextLevel
        queue.push(next+nextLevel*area)
      }
    }
  }
  const rescue=COPS_SPAWNS.rescue
  if(!(connected[tile(Math.floor(rescue.x),Math.floor(rescue.z))]&1))throw Error(`${stage}: rescue pad is unreachable`)
  const runBytes=[]
  for(let i=0;i<area;){
    const mask=connected[i]
    let count=1
    while(count<255&&i+count<area&&connected[i+count]===mask)count++
    runBytes.push(count,mask&255,mask>>8)
    i+=count
  }
  // Cardinal step flags are authored from collision geometry, including overhead clearance.
  const steps=[]
  for(const node of queue){
    const cell=node%area, level=Math.floor(node/area)
    for(let direction=0;direction<4;direction++){
      const next=cell+[-width,-1,1,width][direction]
      if(connected[next]&1<<level)continue
      for(const step of [1,-1]){
        const nextLevel=level+step
        if(nextLevel<0||nextLevel>=levels||!(connected[next]&1<<nextLevel))continue
        if(!(level>0&&stairs[cell]===level)&&!(nextLevel>0&&stairs[next]===nextLevel))continue
        const lower=step>0?cell:next
        if(world.get(minX+lower%width,floor+Math.max(level,nextLevel)+1,minZ+Math.floor(lower/width))!==0)continue
        steps.push([node,direction,next+nextLevel*area])
      }
    }
  }
  maps[stage]={columns:Buffer.from(runBytes).toString('base64'),steps}
}

const contents=`// Generated by online/build-cops-navigation.mjs from the playable arenas.\nexport const navBounds=${JSON.stringify(COPS_BOUNDS)}\nexport const navFloor=${floor}\nexport const navSpawns=${JSON.stringify(COPS_SPAWNS)}\nexport const navMaps=${JSON.stringify(maps)}\n`
const output=new URL('./cops-navigation.mjs',import.meta.url)
if(process.argv.includes('--check')){
  if(readFileSync(output,'utf8').replaceAll('\r\n','\n')!==contents)throw Error('Regenerate cops-navigation.mjs after changing an arena.')
}else writeFileSync(output,contents)
